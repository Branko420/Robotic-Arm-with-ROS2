# Подредба на ставите в цифровия модел на манипулатора.
#
# Списъкът съдържа петте управляеми стави на ръката.
# Хващачът се управлява отделно и не е включен тук.
JOINT_ORDER = [
    # Завъртане на основата.
    "joint_6_base",

    # Става на рамото.
    "joint_5_shoulder",

    # Става на лакътя.
    "joint_4_elbow",

    # Наклон на китката.
    "joint_3_wrist_pitch",

    # Завъртане на китката.
    "joint_2_wrist_roll",
]


# Съответствие между имената на ставите в ROS 2 и RViz
# и имената на физическите сервомотори.
JOINT_TO_SERVO = {
    # Става на основата -> сервомотор на основата.
    "joint_6_base": "base",

    # Става на рамото -> сервомотор на рамото.
    "joint_5_shoulder": "shoulder",

    # Става на лакътя -> сервомотор на лакътя.
    "joint_4_elbow": "elbow",

    # Наклон на китката -> сервомотор на китката.
    "joint_3_wrist_pitch": "wrist",

    # Завъртане на китката -> сервомотор
    # за ротация на китката.
    "joint_2_wrist_roll": "wrist_rotation",
}


# Автоматично създава обратното съответствие:
#
# име на сервомотор -> име на става.
SERVO_TO_JOINT = {
    servo: joint
    for joint, servo in JOINT_TO_SERVO.items()
}


