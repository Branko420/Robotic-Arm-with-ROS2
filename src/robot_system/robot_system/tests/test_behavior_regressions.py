# Позволява отложено оценяване на типовите анотации.
from __future__ import annotations

# Обектно-ориентиран интерфейс
# за работа с файлови пътища.
from pathlib import Path


# Определя кореновата директория на проекта.
#
# __file__ съдържа пътя до текущия тестов файл,
# resolve() го преобразува до абсолютен път,
# а parents[2] избира директорията две нива нагоре.
ROOT = Path(__file__).resolve().parents[2]

# Път до основния Python пакет robot_system.
PACKAGE = ROOT / "robot_system"


def text(relative: str) -> str:
    """
    Прочита съдържанието на файл от пакета robot_system.

    Аргументът relative представлява относителния
    път на файла спрямо директорията robot_system.
    """

    return (PACKAGE / relative).read_text()


def main() -> None:
    """
    Проверява дали основните функционалности,
    необходими за хващане, преместване, поставяне,
    сканиране и естественоезиков отговор,
    са запазени в текущата версия на проекта.
    """

    # Зарежда модула с логиката за:
    # - нормализиране на геометрията;
    # - изчисляване на център;
    # - позиции за хващане и подход.
    targets = text("planning/targets.py")

    # Обединява съдържанието на трите модула,
    # които реализират различните последователности
    # за работа с предмети.
    flows = (
        # Последователност за първоначално хващане.
        text("planning/pick_flow_mixin.py")

        # Пълна последователност за хващане
        # и преместване до крайна цел.
        + text("planning/transfer_flow_mixin.py")

        # Последователност за движение и поставяне
        # на предмет, който вече се държи.
        + text("planning/held_object_flow_mixin.py")
    )

    # Зарежда модула за текущото състояние
    # и безопасното планиране на транзитната височина.
    state = text("planning/state_mixin.py")

    # Обединява интерфейсните инструменти
    # за сканиране и манипулиране.
    tools = (
        text("interfaces/scan_tools.py")
        + text("interfaces/manipulation_tools.py")
    )

    # Зарежда основния разговорен агент,
    # за да провери структурата на отговорите.
    realtime = text("agents/realtime_agent.py")

    # Зарежда конфигурацията с постоянните
    # именувани позиции на манипулатора.
    poses = text("config/permanent_points.json")

    # Проверява дали централната Z координата
    # на предмета присъства в нормализираната геометрия.
    assert '"z": center_z' in targets

    # Проверява дали източникът на Z координатата
    # за хващане е изрично обозначен като center.z.
    assert '"grasp_z_source": "center.z"' in targets

    # Проверява дали е запазена стъпката
    # за подход на точно 3 cm над предмета.
    assert '("approach_3cm", above_xyz)' in flows

    # Проверява дали хващането се извършва
    # в центъра на предмета.
    assert '("grasp_center", pick_xyz)' in flows

    # Проверява дали е запазено вертикалното
    # оттегляне на точно 3 cm след хващането.
    assert '("retreat_3cm", above_xyz)' in flows

    # Проверява дали преди хващането се използва
    # конфигурираната стойност за отваряне на хващача.
    assert (
        'servo_angle_override=PICK_GRIPPER_OPEN_SERVO_DEG'
        in flows
    )

    # Проверява дали съществува методът
    # за изчисляване на безопасна транзитна височина
    # според височината на препятствията.
    assert 'def height_aware_transit_z(' in state

    # Проверява дали интерфейсът поддържа
    # поставяне на вече държан предмет върху цел.
    assert 'def place_held_object_at_target(' in tools

    # Проверява дали при сканиране е запазена
    # минималната продължителност на престоя
    # в позицията за сканиране.
    assert 'SCAN_POSE_MIN_DWELL_SEC' in tools

    # Проверява дали разговорният агент използва
    # структурирани факти при създаване на отговор.
    assert 'response_facts' in realtime

    # Проверява дали инструкцията забранява
    # финален отговор, съдържащ само общо потвърждение.
    assert (
        'Финален отговор, който е само общо потвърждение'
        in realtime
    )

    # Проверява дали в постоянните позиции
    # са запазени необходимите стойности
    # за основата и рамото на позицията за сканиране.
    assert (
        '"base": 0.0' in poses
        and '"shoulder": 31.5' in poses
    )

    # Извежда потвърждение, че нормализирането
    # на геометрията за хващане е запазено.
    print(
        "Pick geometry normalization remains available: OK"
    )

    # Извежда потвърждение, че подходът
    # и оттеглянето на 3 cm са запазени.
    print(
        "Exact 3 cm approach and retreat are preserved: OK"
    )

    # Извежда потвърждение, че предварителното
    # отваряне на хващача до 70 градуса е запазено.
    print(
        "70-degree pre-open is preserved: OK"
    )

    # Извежда потвърждение, че планирането
    # отчита височината на държания предмет
    # и препятствията.
    print(
        "Height-aware held-object planning is preserved: OK"
    )

    # Извежда потвърждение, че естествените
    # структурирани отговори са запазени.
    print(
        "Natural structured realtime responses are preserved: OK"
    )

    # Извежда потвърждение, че позицията за сканиране
    # и минималното време за престой са запазени.
    print(
        "Scan pose and minimum dwell behavior are preserved: OK"
    )


# Стартира теста само когато файлът
# се изпълнява директно.
if __name__ == "__main__":
    main()