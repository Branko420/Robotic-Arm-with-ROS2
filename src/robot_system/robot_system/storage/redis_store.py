# Стандартна библиотека за сериализация
# и десериализация на JSON документи.
import json

# Достъп до променливите на средата.
import os

# Работа с времеви стойности.
import time

# Обща типова анотация за стойности
# с произволен тип.
from typing import Any

# Python клиент за комуникация с Redis.
import redis

# Зарежда конфигурационни стойности
# от .env файл.
from dotenv import load_dotenv


# Зарежда променливите на средата
# от основния .env файл в Docker средата.
load_dotenv("/workspace/.env")


class RedisStore:
    """
    Предоставя общ интерфейс за работа
    с Redis хранилището на системата.

    Класът поддържа:
    - създаване и проверка на Redis връзката;
    - начални стойности за основните състояния;
    - четене и запис на JSON документи;
    - частично обновяване на JSON състояние;
    - добавяне на събития към Redis Stream.
    """

    def __init__(self) -> None:
        """
        Създава Redis клиента, проверява връзката
        и инициализира липсващите начални стойности.
        """

        # Зарежда адреса на Redis от променливата
        # на средата REDIS_URL.
        #
        # По подразбиране се използва локален Redis
        # сървър и база с индекс 0.
        url = os.getenv(
            "REDIS_URL",
            "redis://127.0.0.1:6379/0",
        )

        # Създава Redis клиент.
        #
        # decode_responses=True означава, че Redis
        # връща текстови низове вместо bytes стойности.
        self.client = redis.Redis.from_url(
            url,
            decode_responses=True,
        )

        # Проверява дали Redis сървърът е достъпен.
        #
        # При неуспешна връзка се повдига изключение
        # още при стартирането на модула.
        self.client.ping()

        # Създава липсващите основни състояния.
        self._defaults()

    def _defaults(self) -> None:
        """
        Създава началните Redis стойности,
        когато съответните ключове все още не съществуват.
        """

        # Основни документи със състоянието
        # на робота и работното пространство.
        defaults = {
            # Текущото глобално състояние
            # на роботизирания манипулатор.
            "robot:state": {
                # Основно текстово състояние.
                "state": "IDLE",

                # Показва дали роботът изпълнява задача.
                "busy": False,

                # Показва дали изпълнението е временно спряно.
                "paused": False,

                # Показва дали е заявено незабавно спиране.
                "stop_requested": False,

                # Текущо изпълняваната задача.
                "current_task": None,

                # Предметът, който се държи от хващача.
                "held_object": None,

                # Последно избраният предмет.
                "selected_object": None,

                # Време на последното обновяване.
                "updated_at": time.time(),
            },

            # Текущото състояние
            # на наблюдаваното работно пространство.
            "workspace:state": {
                # Координатна система на предметите.
                "frame": "base_link",

                # Открити предмети.
                "objects": [],

                # Състояние на последното сканиране.
                "scan_state": "NOT_SCANNED",

                # Време на последното обновяване.
                "updated_at": None,
            },
        }

        # Обхожда всички начални документи.
        for key, value in defaults.items():
            # SETNX записва стойността само когато
            # съответният Redis ключ не съществува.
            #
            # Така съществуващото състояние не се заменя
            # при всяко рестартиране на приложението.
            self.client.setnx(
                key,
                json.dumps(value),
            )

    def get_json(
        self,
        key: str,
        default: Any = None,
    ) -> Any:
        """
        Зарежда JSON документ от Redis.

        При липсващ ключ или невалидно JSON съдържание
        връща подадената стойност по подразбиране.
        """

        # Прочита необработената текстова стойност.
        raw = self.client.get(key)

        # Ключът не съществува.
        if raw is None:
            return default

        try:
            # Десериализира JSON съдържанието
            # до Python структура.
            return json.loads(raw)

        except json.JSONDecodeError:
            # При невалиден JSON не прекратява
            # изпълнението на системата.
            return default

    def set_json(
        self,
        key: str,
        value: Any,
    ) -> None:
        """
        Сериализира и записва Python стойност
        като JSON документ в Redis.
        """

        self.client.set(
            key,
            json.dumps(value),
        )

    def update_json(
        self,
        key: str,
        **changes: Any,
    ) -> dict:
        """
        Обновява избрани полета
        в съществуващ JSON документ.

        При липсващ ключ започва с празен речник.
        """

        # Зарежда текущия документ.
        value = self.get_json(
            key,
            {},
        )

        # Добавя или заменя подадените полета.
        value.update(changes)

        # Обновява времето на последната промяна.
        value["updated_at"] = time.time()

        # Записва целия обновен документ.
        self.set_json(
            key,
            value,
        )

        # Връща новото състояние.
        return value

    def add_event(
        self,
        stream: str,
        event: dict,
    ) -> str:
        """
        Добавя събитие към Redis Stream.

        Събитието се записва като JSON документ
        заедно с отделен времеви печат.
        """

        return self.client.xadd(
            stream,
            {
                # Основното съдържание на събитието.
                "payload": json.dumps(event),

                # Време на публикуване на събитието.
                "timestamp": str(time.time()),
            },

            # Ограничава приблизително потока
            # до последните 2000 събития.
            maxlen=2000,
            approximate=True,
        )


# Създава един общ екземпляр на Redis хранилището,
# използван от останалите модули на системата.
store = RedisStore()